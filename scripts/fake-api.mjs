#!/usr/bin/env node
// fake-api.mjs: a stand-in for the backend server, for testing the real (non-mock) API path.
// Dependency-free Node HTTP server. It never talks to SAIDA's systems and holds no real data:
// everything it answers comes from the fictional fixtures in src/mock/fixtures/.
//
// What it imitates (the box = FastAPI behind Caddy, both gated by one basic-auth pair):
//   - basic auth on EVERY path (401 + WWW-Authenticate otherwise), like Caddy in front of both
//   - GET /api/dash/status | stats?days=N | calls?limit&before | calls/:id | bookings?limit
//         | notes?limit | sms?limit, each also with ?reveal=1. Same JSON shapes as the backend
//         (the fixtures are generated by it). FAKE_FIXTURES_DIR points it at another folder in the
//         same layout, e.g. data pulled from the box, to rehearse real mode on real-shaped data. Phone numbers stay masked "(656) ***-0150" unless
//         reveal=1, which answers "(656) 555-0150" (the reserved fictional 555-01xx range).
//         Unknown call id -> 404 {"detail": "call not found"}.
//   - the lead record (voice-agent/handoff/LEADS-PAGE-SPEC-2026-11-04.md), answered by the same
//         module mock mode uses (src/mock/leadStore.ts), kept in memory for the life of the process:
//         GET /api/dash/leads?stage=&limit=&reveal=1 | GET /api/dash/leads/:id | POST
//         /api/dash/leads/:id/action {action, note?, slot_label?} -> {ok, lead}, 422 / 409 / 404
//         with {"error": "<sentence>"}. Seeded from leads-week.json as of yesterday evening, so
//         every weekday and clock time in it is true today and nothing in it is in the future.
//         POST is allowed on that one route only; everything else stays GET / HEAD.
//   - GET /api/dash/stream: real Server-Sent Events. A ": ping" comment every 15 s, and a replay
//         of src/mock/fixtures/stream-sample.txt (event:/data: framing) one event every 2 s,
//         starting 3 s after a stream connects when no replay is running. While the replayed call
//         is live, /status says line "on-call" (live_calls 1), its /calls row is status "live" with
//         ended_at / duration_s null and started_at = when the replay began, and /calls/:id
//         returns only the events sent so far. Replayed events carry the real send time as ts.
//   - optional: GET /dash/* serves a built dist/ (FAKE_DIST=dist), with index.html for every
//         client route (/dash/calls/CA..., /dash/_katie), like the box serving dist at /dash.
//         /dash redirects to /dash/. Hashed /dash/assets/* are cached immutable.
//
// Usage (dummy credentials only; never put a real password here or in a file):
//   FAKE_DASH_USER=demo FAKE_DASH_PASS=not-a-secret node scripts/fake-api.mjs
//   FAKE_DASH_USER=demo FAKE_DASH_PASS=not-a-secret FAKE_DIST=dist FAKE_PORT=5190 node scripts/fake-api.mjs
//
//   Dev proxy against it (no .env.local needed; env vars win over it):
//     DASH_API_TARGET=http://127.0.0.1:5190 DASH_USER=demo DASH_PASS=not-a-secret npx vite --port 5188 --strictPort
//     then open http://localhost:5188/dash/ (no ?mock): every /api/dash request goes through the
//     Vite proxy, which adds the Authorization header; the browser has no credentials.
//   Production topology: npm run build, start this with FAKE_DIST=dist, open
//     http://127.0.0.1:5190/dash/ and sign in with the dummy pair.
//
// Environment:
//   FAKE_DASH_USER, FAKE_DASH_PASS  required; the basic-auth pair (FAKE_NO_AUTH=1 skips the check for a browser-pane rehearsal)
//   FAKE_PORT       default 5190;  FAKE_HOST default 127.0.0.1 (loopback only)
//   FAKE_DIST       a built dist/ directory to serve at /dash/ (relative to the project root)
//   FAKE_EVENT_GAP_MS   default 2000; FAKE_REPLAY_DELAY_MS default 3000; FAKE_PING_MS default 15000
//   FAKE_REPLAY     "0" turns the replay off (the stream then only pings)
//   FAKE_SHIFT_DAYS "auto" (default) moves every fixture timestamp by whole days so the fixtures'
//                   day is today in the practice tz; "0" serves the fixture timestamps unchanged
//   FAKE_LATENCY_MS     added to every JSON answer (default 0)
//
// Test hook: GET /__fake/counters (behind the same auth) returns request counters, never data:
//   { requests, authorized, unauthorized, byPath, streams, openStreams, eventsSent, pings, replay }.
//   It does not count itself.
//
// Stop with Ctrl-C (or SIGTERM); open streams are closed on exit.

import http from 'node:http'
import fs from 'node:fs'
import path from 'node:path'
import crypto from 'node:crypto'
import { fileURLToPath } from 'node:url'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const FIX = process.env.FAKE_FIXTURES_DIR ? path.resolve(process.env.FAKE_FIXTURES_DIR) : path.join(ROOT, 'src/mock/fixtures')

const USER = process.env.FAKE_DASH_USER
const PASS = process.env.FAKE_DASH_PASS
if (!USER || !PASS) {
  console.error('fake-api: set FAKE_DASH_USER and FAKE_DASH_PASS (dummy values) to start.')
  process.exit(2)
}
const PORT = Number(process.env.FAKE_PORT || 5190)
const HOST = process.env.FAKE_HOST || '127.0.0.1'
const DIST = process.env.FAKE_DIST ? path.resolve(ROOT, process.env.FAKE_DIST) : null
const EVENT_GAP_MS = Number(process.env.FAKE_EVENT_GAP_MS || 2000)
const REPLAY_DELAY_MS = Number(process.env.FAKE_REPLAY_DELAY_MS || 3000)
const PING_MS = Number(process.env.FAKE_PING_MS || 15000)
const REPLAY_ON = process.env.FAKE_REPLAY !== '0'
const LATENCY_MS = Number(process.env.FAKE_LATENCY_MS || 0)

// ------------------------------------------------------------------ fixtures

const readJson = (name) => JSON.parse(fs.readFileSync(path.join(FIX, name), 'utf8'))
const STATUS = readJson('status.json')
const STATS1 = readJson('stats.json')
const STATS7 = readJson('stats-7d.json')
const CALLS = readJson('calls.json').calls
const BOOKINGS = readJson('bookings.json').bookings
const NOTES = readJson('notes.json').notes
const SMS = readJson('sms.json').sms
const DETAILS = new Map()
for (const f of fs.readdirSync(FIX)) {
  if (/^call-.+\.json$/.test(f)) {
    const d = readJson(f)
    DETAILS.set(d.call.call_id, d)
  }
}
const TZ = STATS1.range.tz || 'America/New_York'

// The lead record: src/mock/leadStore.ts mirrors voice-agent/leads.py rule for rule (Node strips
// the types on import). A fixtures folder without lead files (data pulled from the box before
// leads existed) serves an empty record.
const leadStore = await import(new URL('../src/mock/leadStore.ts', import.meta.url).href)
const hasFixture = (name) => fs.existsSync(path.join(FIX, name))
const LEADS = leadStore.createLeadStore(
  hasFixture('leads-week.json')
    ? leadStore.seedForDate(readJson('leads-week.json'), Date.now() / 1000 - 86_400)
    : hasFixture('leads.json')
      ? readJson('leads.json')
      : null,
)

/** stream-sample.txt as [{ kind, data: <parsed JSON> }], comments skipped. */
function parseStream(raw) {
  const out = []
  for (const block of raw.split(/\r?\n\r?\n/)) {
    let kind = ''
    let data = ''
    for (const line of block.split(/\r?\n/)) {
      if (line.startsWith(':')) continue
      if (line.startsWith('event:')) kind = line.slice(6).trim()
      else if (line.startsWith('data:')) data += line.slice(5).trim()
    }
    if (kind && data) out.push({ kind, data: JSON.parse(data) })
  }
  return out
}
const STREAM = parseStream(fs.readFileSync(path.join(FIX, 'stream-sample.txt'), 'utf8'))

// ------------------------------------------------------------------ time

const nowSec = () => Date.now() / 1000

function tzOffsetSec(ts, tz) {
  const parts = new Intl.DateTimeFormat('en-US', {
    timeZone: tz,
    hourCycle: 'h23',
    year: 'numeric',
    month: '2-digit',
    day: '2-digit',
    hour: '2-digit',
    minute: '2-digit',
    second: '2-digit',
  }).formatToParts(new Date(ts * 1000))
  const p = Object.fromEntries(parts.map((x) => [x.type, Number(x.value)]))
  const asUtc = Date.UTC(p.year, p.month - 1, p.day, p.hour, p.minute, p.second)
  return (asUtc - Math.floor(ts) * 1000) / 1000
}

/** Local midnight in tz of the day `daysBack` days before the day containing ts (UNIX s). */
function zonedMidnight(ts, tz, daysBack = 0) {
  const local = new Date((ts + tzOffsetSec(ts, tz)) * 1000)
  const guessUtc = Date.UTC(local.getUTCFullYear(), local.getUTCMonth(), local.getUTCDate() - daysBack) / 1000
  let t = guessUtc - tzOffsetSec(guessUtc, tz)
  t = guessUtc - tzOffsetSec(t, tz)
  return t
}

// Whole-day shift so the fixtures' day is today (DST-safe: difference of two local midnights).
const SHIFT = (() => {
  const v = (process.env.FAKE_SHIFT_DAYS ?? 'auto').trim()
  if (v === 'auto') return zonedMidnight(nowSec(), TZ) - zonedMidnight(STATUS.now, TZ)
  const n = Number(v) || 0
  return n === 0 ? 0 : zonedMidnight(STATUS.now, TZ, -n) - zonedMidnight(STATUS.now, TZ)
})()
const TS_KEYS = new Set(['ts', 'started_at', 'ended_at', 'last_call_at', 'boot_at', 'now', 'from', 'to'])

/** Deep copy with every timestamp moved by SHIFT. */
function shifted(v, key) {
  if (typeof v === 'number') return SHIFT && key && TS_KEYS.has(key) ? v + SHIFT : v
  if (Array.isArray(v)) return v.map((x) => shifted(x))
  if (v && typeof v === 'object') {
    const out = {}
    for (const [k, x] of Object.entries(v)) out[k] = shifted(x, k)
    return out
  }
  return v
}

// ------------------------------------------------------------------ reveal

const MASKED = /^(\(\d{3}\) )\*\*\*(-\d{4})$/
function unmask(v) {
  if (typeof v === 'string') return MASKED.test(v) ? v.replace(MASKED, '$1555$2') : v
  if (Array.isArray(v)) return v.map(unmask)
  if (v && typeof v === 'object') {
    const out = {}
    for (const [k, x] of Object.entries(v)) out[k] = unmask(x)
    return out
  }
  return v
}

// ------------------------------------------------------------------ live replay state

const clients = new Set() // open SSE responses
const replay = { running: false, index: 0, liveCallId: null, liveStartedAt: null, emitted: new Map(), timer: null }
const counters = { requests: 0, authorized: 0, unauthorized: 0, byPath: {}, streams: 0, eventsSent: 0, pings: 0 }

function broadcast(text) {
  for (const res of clients) res.write(text)
}

function startReplay() {
  if (!REPLAY_ON || replay.running) return
  replay.running = true
  replay.index = 0
  const step = () => {
    const ev = STREAM[replay.index]
    if (!ev) {
      replay.running = false
      replay.timer = null
      return
    }
    const ts = nowSec()
    const payload = { ...ev.data, ts }
    const id = payload.call_id
    if (ev.kind === 'call.started') {
      replay.liveCallId = id
      replay.liveStartedAt = ts
      replay.emitted.set(id, 0)
    }
    replay.emitted.set(id, (replay.emitted.get(id) ?? 0) + 1)
    if (ev.kind === 'call.ended' && replay.liveCallId === id) {
      replay.liveCallId = null
      replay.liveStartedAt = null
      replay.emitted.delete(id)
    }
    // Real SSE framing: event name, one data line of JSON, blank line.
    broadcast(`event: ${ev.kind}\ndata: ${JSON.stringify(payload)}\n\n`)
    counters.eventsSent += clients.size
    replay.index += 1
    replay.timer = setTimeout(step, EVENT_GAP_MS)
  }
  replay.timer = setTimeout(step, REPLAY_DELAY_MS)
}

function liveRow(row) {
  return { ...row, status: 'live', disposition: 'live', ended_at: null, duration_s: null, started_at: replay.liveStartedAt }
}

// ------------------------------------------------------------------ API routes

function statsBody(daysParam) {
  const days = Math.min(90, Math.max(1, Math.floor(Number(daysParam) || 1)))
  const out = shifted(days === 1 ? STATS1 : STATS7)
  const from1 = shifted(STATS1).range.from
  out.range = { ...out.range, days, from: days === 1 ? from1 : zonedMidnight(from1, TZ, days - 1), to: nowSec() }
  return out
}

function apiRoute(p, q) {
  if (p === '/status') {
    const live = !!replay.liveCallId
    return [200, { ...shifted(STATUS), now: nowSec(), line: live ? 'on-call' : 'idle', live_calls: live ? 1 : 0 }]
  }
  if (p === '/stats') return [200, statsBody(q.get('days'))]
  if (p === '/calls') {
    const limit = Math.max(1, Math.floor(Number(q.get('limit')) || 50))
    const before = q.get('before') ? Number(q.get('before')) : Infinity
    const rows = shifted(CALLS)
      .filter((c) => c.started_at < before)
      .slice(0, limit)
      .map((c) => (c.call_id === replay.liveCallId ? liveRow(c) : c))
    return [200, { calls: rows }]
  }
  const m = /^\/calls\/([^/]+)$/.exec(p)
  if (m) {
    let id
    try {
      id = decodeURIComponent(m[1])
    } catch {
      return [404, { detail: 'call not found' }]
    }
    const d = DETAILS.get(id)
    if (!d) return [404, { detail: 'call not found' }]
    const out = shifted(d)
    if (id === replay.liveCallId) {
      out.call = liveRow(out.call)
      out.events = out.events.slice(0, replay.emitted.get(id) ?? 0)
    }
    return [200, out]
  }
  const list = (key, rows) => {
    const limit = Math.max(1, Math.floor(Number(q.get('limit')) || 50))
    return [200, { [key]: shifted(rows).slice(0, limit) }]
  }
  // The public sign-in config (src/auth/config.ts): this stand-in box is the basic-auth kind.
  if (p === '/config') return [200, { auth: 'basic', idle_minutes: 15, remember_days: 30, support_email: 'support@example.com' }]
  if (p === '/bookings') return list('bookings', BOOKINGS)
  if (p === '/notes') return list('notes', NOTES)
  if (p === '/sms') return list('sms', SMS)
  return [404, { detail: 'Not Found' }]
}

function sendJson(res, status, body, headOnly) {
  const text = JSON.stringify(body)
  res.writeHead(status, {
    'Content-Type': 'application/json',
    'Content-Length': Buffer.byteLength(text),
    'Cache-Control': 'no-store',
  })
  res.end(headOnly ? undefined : text)
}

/** A request's JSON body (64 KB cap); anything unreadable is null, which the route refuses. */
function readBody(req) {
  return new Promise((resolve) => {
    const chunks = []
    let size = 0
    req.on('data', (c) => {
      size += c.length
      if (size <= 65_536) chunks.push(c)
    })
    req.on('end', () => {
      if (size > 65_536) return resolve(null)
      try {
        resolve(JSON.parse(Buffer.concat(chunks).toString('utf8')))
      } catch {
        resolve(null)
      }
    })
    req.on('error', () => resolve(null))
  })
}

function openStream(req, res) {
  counters.streams += 1
  res.writeHead(200, {
    'Content-Type': 'text/event-stream; charset=utf-8',
    'Cache-Control': 'no-cache',
    Connection: 'keep-alive',
    'X-Accel-Buffering': 'no',
  })
  res.write(': connected\n\n')
  clients.add(res)
  const ping = setInterval(() => {
    res.write(': ping\n\n')
    counters.pings += 1
  }, PING_MS)
  const done = () => {
    clearInterval(ping)
    clients.delete(res)
  }
  req.on('close', done)
  res.on('error', done)
  startReplay()
}

// ------------------------------------------------------------------ static dist at /dash/

const TYPES = {
  '.html': 'text/html; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8',
  '.mjs': 'text/javascript; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.json': 'application/json',
  '.map': 'application/json',
  '.svg': 'image/svg+xml',
  '.png': 'image/png',
  '.webp': 'image/webp',
  '.jpg': 'image/jpeg',
  '.ico': 'image/x-icon',
  '.woff2': 'font/woff2',
  '.txt': 'text/plain; charset=utf-8',
}

function serveDist(req, res, pathname, headOnly) {
  if (!DIST) return sendJson(res, 404, { detail: 'Not Found' }, headOnly)
  if (pathname === '/dash') {
    res.writeHead(301, { Location: '/dash/' })
    return res.end()
  }
  let rel
  try {
    rel = decodeURIComponent(pathname.slice('/dash/'.length))
  } catch {
    return sendJson(res, 400, { detail: 'Bad path' }, headOnly)
  }
  const file = path.resolve(DIST, rel)
  if (file !== DIST && !file.startsWith(DIST + path.sep)) return sendJson(res, 404, { detail: 'Not Found' }, headOnly)
  let target = file
  let stat = null
  try {
    stat = fs.statSync(target)
    if (stat.isDirectory()) {
      target = path.join(target, 'index.html')
      stat = fs.statSync(target)
    }
  } catch {
    stat = null
  }
  if (!stat) {
    // A missing hashed asset is a real 404 (a stale tab must not get HTML for a script);
    // anything else is a client route and gets the app shell.
    if (rel.startsWith('assets/')) return sendJson(res, 404, { detail: 'Not Found' }, headOnly)
    target = path.join(DIST, 'index.html')
    try {
      stat = fs.statSync(target)
    } catch {
      return sendJson(res, 404, { detail: 'dist/index.html missing: run npm run build' }, headOnly)
    }
  }
  const ext = path.extname(target).toLowerCase()
  res.writeHead(200, {
    'Content-Type': TYPES[ext] || 'application/octet-stream',
    'Content-Length': stat.size,
    'Cache-Control': rel.startsWith('assets/') && target !== path.join(DIST, 'index.html') ? 'public, max-age=31536000, immutable' : 'no-cache',
  })
  if (headOnly) return res.end()
  fs.createReadStream(target).pipe(res)
}

// ------------------------------------------------------------------ server

const EXPECTED = Buffer.from('Basic ' + Buffer.from(`${USER}:${PASS}`).toString('base64'))
const NO_AUTH = process.env.FAKE_NO_AUTH === '1' // pane rehearsals only: a browser pane cannot answer the auth prompt
function authorized(req) {
  if (NO_AUTH) return true
  const got = Buffer.from(String(req.headers.authorization || ''))
  return got.length === EXPECTED.length && crypto.timingSafeEqual(got, EXPECTED)
}

const server = http.createServer((req, res) => {
  const url = new URL(req.url || '/', 'http://fake.local')
  const pathname = url.pathname
  const isCounters = pathname === '/__fake/counters'
  if (!isCounters) counters.requests += 1

  if (!authorized(req)) {
    if (!isCounters) counters.unauthorized += 1
    res.writeHead(401, {
      'WWW-Authenticate': 'Basic realm="Katie dashboard (fake)", charset="UTF-8"',
      'Content-Type': 'text/plain; charset=utf-8',
    })
    return res.end('Unauthorized\n')
  }
  if (isCounters) {
    return sendJson(res, 200, {
      ...counters,
      openStreams: clients.size,
      replay: { running: replay.running, index: replay.index, live: !!replay.liveCallId },
    })
  }
  counters.authorized += 1

  const apiPath = pathname.startsWith('/api/dash/') ? pathname.slice('/api/dash'.length).replace(/\/+$/, '') : null
  const isLeadAction = apiPath !== null && /^\/leads\/[^/]+\/action$/.test(apiPath)
  // The one write the dashboard makes: a coordinator's tap on a lead.
  if (req.method === 'POST' && isLeadAction) {
    counters.byPath['POST /leads/:id/action'] = (counters.byPath['POST /leads/:id/action'] ?? 0) + 1
    return void readBody(req).then((body) => {
      const r = leadStore.leadsRoute(LEADS, 'POST', apiPath, url.searchParams, body, nowSec())
      const send = () => sendJson(res, r.status, r.body, false)
      if (LATENCY_MS > 0) setTimeout(send, LATENCY_MS)
      else send()
    })
  }
  if (req.method !== 'GET' && req.method !== 'HEAD') {
    res.writeHead(405, { Allow: isLeadAction ? 'POST' : 'GET, HEAD' })
    return res.end()
  }
  const headOnly = req.method === 'HEAD'

  if (apiPath !== null) {
    const p = apiPath
    const bucket = /^\/calls\/.+/.test(p) ? '/calls/:id' : /^\/leads\/[^/]+\/action$/.test(p) ? '/leads/:id/action' : /^\/leads\/.+/.test(p) ? '/leads/:id' : p
    counters.byPath[bucket] = (counters.byPath[bucket] ?? 0) + 1
    if (p === '/stream') return openStream(req, res)
    // Leads answer for themselves, reveal included (ten digits, as the box sends them).
    const lead = leadStore.leadsRoute(LEADS, 'GET', p, url.searchParams, undefined, nowSec())
    if (lead) {
      if (LATENCY_MS > 0) return void setTimeout(() => sendJson(res, lead.status, lead.body, headOnly), LATENCY_MS)
      return sendJson(res, lead.status, lead.body, headOnly)
    }
    const [status, body] = apiRoute(p, url.searchParams)
    const reveal = url.searchParams.get('reveal') === '1'
    const out = status === 200 && reveal ? unmask(body) : body
    if (LATENCY_MS > 0) return void setTimeout(() => sendJson(res, status, out, headOnly), LATENCY_MS)
    return sendJson(res, status, out, headOnly)
  }
  if (pathname === '/dash' || pathname.startsWith('/dash/')) return serveDist(req, res, pathname, headOnly)
  if (pathname === '/') {
    res.writeHead(302, { Location: '/dash/' })
    return res.end()
  }
  return sendJson(res, 404, { detail: 'Not Found' }, headOnly)
})

server.listen(PORT, HOST, () => {
  const shiftDays = Math.round(SHIFT / 86400)
  console.log(
    `fake-api: http://${HOST}:${PORT}  (basic auth on every path; dist ${DIST ? path.relative(ROOT, DIST) || '.' : 'off'};` +
      ` replay ${REPLAY_ON ? `${EVENT_GAP_MS} ms` : 'off'}; fixture days shifted ${shiftDays})`,
  )
})

function shutdown() {
  clearTimeout(replay.timer)
  for (const res of clients) res.end()
  clients.clear()
  server.close(() => process.exit(0))
  setTimeout(() => process.exit(0), 500).unref()
}
process.on('SIGINT', shutdown)
process.on('SIGTERM', shutdown)
